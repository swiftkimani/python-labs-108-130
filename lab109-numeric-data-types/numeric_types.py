# AWS re/Start - Python Programming

# Integer
count = 25
print("count =", count)
print("type:", type(count))

# Float
price = 19.99
print("\nprice =", price)
print("type:", type(price))

# Complex
number = 3 + 4j
print("\nnumber =", number)
print("type:", type(number))

# Arithmetic operators
a = 17
b = 5

print("\nArithmetic with a =", a, "and b =", b)
print("a + b  =", a + b)
print("a - b  =", a - b)
print("a * b  =", a * b)
print("a / b  =", a / b)
print("a // b =", a // b)
print("a % b  =", a % b)
print("a ** b =", a ** b)

# Converting between types
print("\nType conversion")
print('int("42")  =', int("42"))
print("int(3.9)   =", int(3.9))
print("float(7)   =", float(7))
print("str(99)    =", str(99))
print("round(3.7) =", round(3.7))

# Built-in numeric functions
print("\nBuilt-in functions")
print("abs(-7)        =", abs(-7))
print("pow(2, 10)     =", pow(2, 10))
print("max(3, 9, 2)   =", max(3, 9, 2))
print("min(3, 9, 2)   =", min(3, 9, 2))
print("sum([1, 2, 3]) =", sum([1, 2, 3]))
